// File discovery: walk order gives file ids; per-file byte statistics.
import * as fs from "dyna:file";
import { SHA1Hex } from "dyna:hash";
import { encode } from "dyna:bytes";
import { readBytesString, cleanPath, basename } from "./pp.js";

const SKIP_DIRS = new Set((".git .hg .svn .jj .idea .vscode .vs .claude node_modules bower_components vendor third_party thirdparty " +
  "external externals deps Godeps _vendor __pycache__ .mypy_cache .pytest_cache .ruff_cache .tox .venv venv env .env virtualenv " +
  "build _build dist out target bin obj .gradle .next .nuxt .svelte-kit .parcel-cache .turbo .cache coverage htmlcov .nyc_output " +
  "site-packages CMakeFiles .deps .libs autom4te.cache").split(" "));
const C_EXTS = new Set([".c", ".h", ".inc", ".cc"]);
const MAX_FILE = 4 << 20, MAX_LINE = 1 << 20;
const TEST_SEGS = ["test", "tests", "test-d", "spec", "specs", "__tests__", "__snapshots__", "testing", "e2e", "integration-tests",
  "integration_tests", "testdata", "test_data", "test-data", "fixture", "fixtures"];
const VENDOR_SEGS = ["vendor", "third_party", "thirdparty", "external", "node_modules", "deps"];
const GEN_MARKERS = ["@generated", "DO NOT EDIT", "Code generated by", "AUTO-GENERATED", "autogenerated",
  "This file was automatically generated", "Generated by the protocol buffer compiler", "@flow-generated"];
const GEN_NAME = [".min.", ".bundle.", ".gen.", ".generated.", ".pb.", ".g.", "_pb2", ".designer."];

export const segMatch = (p, words) => p.toLowerCase().split("/").some((s) => words.includes(s));
export const isTestPath = (rel) => segMatch(rel, TEST_SEGS);
export const isVendorPath = (rel) => segMatch(rel, VENDOR_SEGS);

export function moduleOf(rel) {
  const parts = rel.split("/");
  if (parts.length <= 1) return "(root)";
  let head = parts.slice(0, -1);
  head = head.slice(0, ["src", "lib", "source", "internal", "pkg", "app"].includes(head[0]) ? 3 : 2);
  return head.join("/");
}

export function moduleKind(name) {
  if (isTestPath(name)) return "test";
  if (isVendorPath(name)) return "vendor";
  if (segMatch(name, ["example", "examples", "sample", "samples", "demo", "demos"])) return "example";
  if (segMatch(name, ["tool", "tools", "script", "scripts", "cmd", "bin"])) return "tool";
  return "source";
}

function isGenerated(fn, head) {
  const lower = fn.toLowerCase();
  if (GEN_NAME.some((p) => lower.includes(p)) || lower.endsWith(".g.dart") || lower.startsWith("zz_generated")) return true;
  return GEN_MARKERS.some((m) => head.includes(m));
}

export function runeLen(s, a = 0, b = s.length) {
  let n = b - a;
  for (let i = a; i < b; i++) if ((s.charCodeAt(i) & 0xc0) === 0x80) n--;
  return n;
}

// Width in bytes of a line boundary at i, or 0.
export function boundaryAt(s, i) {
  const c = s.charCodeAt(i);
  switch (c) {
    case 10: case 11: case 12: case 0x1c: case 0x1d: case 0x1e: return 1;
    case 13: return s.charCodeAt(i + 1) === 10 ? 2 : 1;
    case 0xc2: return s.charCodeAt(i + 1) === 0x85 ? 2 : 0;
    case 0xe2: return s.charCodeAt(i + 1) === 0x80 && (s.charCodeAt(i + 2) === 0xa8 || s.charCodeAt(i + 2) === 0xa9) ? 3 : 0;
  }
  return 0;
}

const BOUNDARY_RE = /[\n\r\x0b\x0c\x1c-\x1e\xc2\xe2]/g;

export function lineStats(s) {
  let n = 0, maxLen = 0, start = 0;
  BOUNDARY_RE.lastIndex = 0;
  let m;
  while ((m = BOUNDARY_RE.exec(s)) !== null) {
    const i = m.index, w = boundaryAt(s, i);
    if (w === 0) continue;
    const r = runeLen(s, start, i);
    if (r > maxLen) maxLen = r;
    n++;
    start = i + w;
    BOUNDARY_RE.lastIndex = start;
  }
  if (start < s.length) { n++; const r = runeLen(s, start, s.length); if (r > maxLen) maxLen = r; }
  return { n, maxLen };
}

// Code / comment-only line counts (blank lines are derived by the caller).
const CL_ANY = /[\n\r\/"']/g, CL_NWS = /[^ \t\f\v]/g, CL_BLK = /\*\/|[\n\r]|[^ \t]/g, CL_BLK2 = /\*\/|[\n\r]/g;
const CL_EOL = /[\n\r]/g, CL_DQ = /["\\\n\r]/g, CL_SQ = /['\\\n\r]/g;
export function classifyLines(b) {
  let code = 0, cmt = 0, inBlock = false, hasCode = false, hasCmt = false;
  const n = b.length;
  let i = 0;
  while (i < n) {
    let c;
    if (inBlock) {
      const re = hasCmt ? CL_BLK2 : CL_BLK;
      re.lastIndex = i;
      const m = re.exec(b);
      if (m === null) break;
      const p = m.index;
      if (m[0].length === 2) { inBlock = false; hasCmt = true; i = p + 2; continue; }
      c = b.charCodeAt(p);
      if (c !== 10 && c !== 13) { hasCmt = true; i = p + 1; continue; }
      i = p;
    } else {
      const re = hasCode ? CL_ANY : CL_NWS;
      re.lastIndex = i;
      if (re.exec(b) === null) break;
      i = re.lastIndex - 1;
      c = b.charCodeAt(i);
    }
    if (c === 10 || c === 13) {
      if (c === 13 && b.charCodeAt(i + 1) === 10) i++;
      if (hasCode) code++; else if (hasCmt) cmt++;
      hasCode = hasCmt = false;
      i++;
      continue;
    }
    if (c === 47) {
      const d = b.charCodeAt(i + 1);
      if (d === 47) {
        hasCmt = true;
        CL_EOL.lastIndex = i + 1;
        i = CL_EOL.exec(b) === null ? n : CL_EOL.lastIndex - 1;
      } else if (d === 42) { inBlock = hasCmt = true; i += 2; }
      else { hasCode = true; i++; }
      continue;
    }
    if (c === 34 || c === 39) {
      hasCode = true;
      const re = c === 34 ? CL_DQ : CL_SQ;
      let j = i + 1;
      for (;;) {
        re.lastIndex = j;
        if (re.exec(b) === null) { i = n; break; }
        const p = re.lastIndex - 1, d = b.charCodeAt(p);
        if (d === 92) { j = p + 1 < n && b.charCodeAt(p + 1) !== 10 && b.charCodeAt(p + 1) !== 13 ? p + 2 : p + 1; continue; }
        i = d === c ? p + 1 : p;
        break;
      }
      continue;
    }
    hasCode = true;
    i++;
  }
  if (hasCode || hasCmt) { if (hasCode) code++; else if (hasCmt) cmt++; }
  return { code, cmt };
}

function hasLongLine(s) {
  let p = 0;
  for (;;) {
    const e = s.indexOf("\n", p);
    if ((e < 0 ? s.length : e) - p > MAX_LINE) return true;
    if (e < 0) return false;
    p = e + 1;
  }
}

function joinPath(dir, name) { return cleanPath(dir + "/" + name); }

// Returns { files, modules, stats, parse:[ids], data: Map(id -> bytes) }.
export function discover(root, opts) {
  root = cleanPath(root);
  const stats = { walkErrors: 0, skippedSpecial: 0, skippedEscape: 0, skippedDenied: 0, skippedBig: 0 };
  let realRoot = root;
  try { realRoot = String(fs.realPath(new fs.Path(root))); } catch (e) {}
  const cands = [];
  const consider = (full, fn, viaLink) => {
    const dot = fn.lastIndexOf(".");
    const ext = dot < 0 ? "" : fn.slice(dot);
    if (!C_EXTS.has(ext)) return;
    let st;
    try { st = fs.stat(new fs.Path(full)); } catch (e) { return; }
    if (!st.isFile) { stats.skippedSpecial++; return; }
    if (viaLink) {
      let rp = full;
      try { rp = String(fs.realPath(new fs.Path(full))); } catch (e) {}
      if (rp !== full && !rp.startsWith(realRoot + "/")) { stats.skippedEscape++; return; }
    }
    cands.push({ full, fn, ext, tooBig: st.size > MAX_FILE });
  };
  const walk = (dir, viaLink) => {
    let ents;
    try { ents = fs.readDir(new fs.Path(dir)); } catch (e) { stats.walkErrors++; return; }
    const files = [], dirs = [];
    for (const e of ents) {
      if (e.isSymlink) {
        let st;
        try { st = fs.stat(new fs.Path(joinPath(dir, e.name))); } catch (x) { continue; }
        (st.isDir ? dirs : files).push({ name: e.name, link: true });
      } else (e.isDir ? dirs : files).push({ name: e.name, link: false });
    }
    const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
    files.sort(byName); dirs.sort(byName);
    for (const e of files) consider(joinPath(dir, e.name), e.name, viaLink || e.link);
    for (const e of dirs) {
      if (e.link || SKIP_DIRS.has(e.name) || e.name.startsWith(".")) continue;
      walk(joinPath(dir, e.name), viaLink);
    }
  };
  walk(root, false);

  const files = [], modules = [], modID = new Map(), data = new Map(), parse = [];
  const rootPrefix = root === "." ? "" : root + "/";
  for (const c of cands) {
    let bytes = "";
    let longLine = false;
    if (!c.tooBig) {
      try { bytes = readBytesString(c.full); } catch (e) { stats.skippedDenied++; continue; }
      longLine = hasLongLine(bytes);
    }
    const tooBig = c.tooBig || longLine;
    if (tooBig) stats.skippedBig++;
    const rel = c.full.startsWith(rootPrefix) ? c.full.slice(rootPrefix.length) : basename(c.full);
    const test = isTestPath(rel) || c.fn.startsWith("test_") || c.fn.startsWith("t_") || c.fn.endsWith("_test.c") || c.fn.endsWith("_test.h");
    const gen = isGenerated(c.fn, bytes.slice(0, 2000));
    const vend = isVendorPath(rel);
    const modName = moduleOf(rel);
    let mid = modID.get(modName);
    if (mid === undefined) {
      mid = modules.length + 1;
      modID.set(modName, mid);
      modules.push({ id: mid, name: modName, kind: moduleKind(modName) });
    }
    const parsed = !tooBig && bytes.length !== 0 && (opts.includeTests || !test) && (opts.includeGenerated || !gen) && (opts.includeVendored || !vend);
    const id = files.length + 1;
    const slash = rel.lastIndexOf("/");
    files.push({
      id, path: rel, full: c.full, dir: slash < 0 ? "." : rel.slice(0, slash), basename: c.fn, ext: c.ext, lang: "c", moduleID: mid,
      bytes: bytes.length, lines: 0, sloc: 0, blankLines: 0, commentLines: 0, docLines: 0, maxLineLen: 0, sha1: "", parsed: parsed ? 1 : 0,
      isTest: test ? 1 : 0, isGenerated: gen ? 1 : 0, isVendored: vend ? 1 : 0,
      nParseErrors: 0, nMissingNodes: 0, nSymbols: 0, nFunctions: 0, nTypes: 0, nImports: 0, totalCyclo: 0, maxCyclo: 0, totalRisk: 0,
    });
    data.set(id, bytes);
    if (parsed) parse.push(id);
  }
  return { root, files, modules, stats, parse, data };
}

// The per-file statistics of the files table: [lines, maxLineLen, sloc, blank, comment, sha1].
export function fileStats(bytes) {
  const ls = lineStats(bytes), cl = classifyLines(bytes);
  return [ls.n, ls.maxLen, cl.code, Math.max(ls.n - cl.code - cl.cmt, 0), cl.cmt, bytes.length ? sha1Latin1(bytes) : ""];
}

export function applyStats(f, st) {
  f.lines = st[0]; f.maxLineLen = st[1]; f.sloc = st[2]; f.blankLines = st[3]; f.commentLines = st[4]; f.sha1 = st[5];
}

function sha1Latin1(s) {
  return SHA1Hex(encode(s, "iso-8859-1"));
}
