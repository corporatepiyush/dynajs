#!/bin/sh
# Builds dynajs with dyna:sdl + dyna:ui into an Android APK (arm64-v8a) and drives
# it on a device or emulator. Everything lands in .obj-android/ (gitignored).
#
#   tools/android/build-apk.sh build APP.js      SDL3 for Android, the engine, libmain.so, the APK
#   tools/android/build-apk.sh emulator          create (once) and boot the "dynajs" AVD, headless
#   tools/android/build-apk.sh run APP.js        build, install, launch; prints the app's log. The script
#                                                gets --window, as examples/ui/*.js expect for a window
#   tools/android/build-apk.sh log               the running app's stdout/stderr
#   tools/android/build-apk.sh smoke             build, install and drive demo.js; checks taps, fling,
#                                                long press, resume repaint and the keyboard (smoke.py)
#
# The engine is compiled from the host build's own compile lines (build.sh __cc-lines),
# retargeted to the NDK's clang, so flags cannot drift from the desktop build.
# Needs: the host build done once (repl.c is generated by it), Homebrew's
# android-commandlinetools + android-ndk, and the SDK packages platform-tools,
# platforms;android-35, build-tools;35.0.1, emulator, system-images;android-35;default;arm64-v8a.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT=${ANDROID_OUT:-$ROOT/.obj-android}
NDK=${ANDROID_NDK_HOME:-/opt/homebrew/share/android-ndk}
SDK=${ANDROID_HOME:-/opt/homebrew/share/android-commandlinetools}
API=${ANDROID_API:-28}
ABI=arm64-v8a
PKG=org.dynajs.app
SDL_VER=3.4.20
SDL_SHA=f3bb06f55bed9557227a700af2ea62e49497ebdf58037732a731a5fb3ef8581f
SDL_URL=https://github.com/libsdl-org/SDL/releases/download/release-$SDL_VER/SDL3-$SDL_VER.tar.gz
SDL_SRC=$ROOT/third_party/android/SDL3-$SDL_VER
AVD=dynajs

die(){ echo "android: $*" >&2; exit 1; }

tools_find(){
  TC=$(ls -d "$NDK"/toolchains/llvm/prebuilt/* 2>/dev/null | head -1)
  [ -n "$TC" ] || die "no NDK at $NDK (brew install --cask android-ndk, or set ANDROID_NDK_HOME)"
  CC="$TC/bin/clang --target=aarch64-linux-android$API"
  BT=$(ls -d "$SDK"/build-tools/* 2>/dev/null | sort -V | tail -1)
  JAR=$(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1)
  ADB=$SDK/platform-tools/adb
  [ -n "$BT" ] && [ -n "$JAR" ] || die "no build-tools/platform under $SDK (see the header of this script)"
}

sdl_build(){
  [ -f "$OUT/sdl3-$SDL_VER/lib/libSDL3.so" ] && return 0
  if [ ! -d "$SDL_SRC" ]; then
    mkdir -p "$ROOT/third_party/android/dl"
    tgz=$ROOT/third_party/android/dl/SDL3-$SDL_VER.tar.gz
    [ -f "$tgz" ] || curl -fsSL -o "$tgz" "$SDL_URL"
    got=$(shasum -a 256 "$tgz" | cut -d' ' -f1)
    [ "$got" = "$SDL_SHA" ] || die "SDL3-$SDL_VER.tar.gz sha256 is $got, expected $SDL_SHA"
    tar -xzf "$tgz" -C "$ROOT/third_party/android"
  fi
  echo "android: building SDL3 $SDL_VER for $ABI (API $API)"
  cmake -S "$SDL_SRC" -B "$OUT/sdl3-$SDL_VER-build" -G Ninja -DCMAKE_TOOLCHAIN_FILE="$NDK/build/cmake/android.toolchain.cmake" \
    -DANDROID_ABI=$ABI -DANDROID_PLATFORM="android-$API" -DCMAKE_BUILD_TYPE=Release -DSDL_SHARED=ON -DSDL_STATIC=OFF \
    -DSDL_TEST_LIBRARY=OFF -DSDL_TESTS=OFF -DSDL_EXAMPLES=OFF -DCMAKE_INSTALL_PREFIX="$OUT/sdl3-$SDL_VER" > "$OUT/sdl3.log" 2>&1 \
    && cmake --build "$OUT/sdl3-$SDL_VER-build" >> "$OUT/sdl3.log" 2>&1 \
    && cmake --install "$OUT/sdl3-$SDL_VER-build" >> "$OUT/sdl3.log" 2>&1 || die "SDL3 build failed -- log: $OUT/sdl3.log"
}

# The objects the APK links: the engine library, the CLI (its main renamed), the
# native-module core, dyna:file and the net family, and the two UI modules. An include
# list: anything else stays out. MODULE_DEFINES are the registration switches kept.
ENGINE_OBJS="dyna-cli repl dynajs engine-parser engine-serialize dtoa libregexp libunicode cutils dyna-libc dyna-io
dyn-hash dyn-codec dyn-prng dyn-compress dyn-ds dyn-serial dyn-path dyn-mathx dyn-ac dyn-dict dyn-pool dyn-timer dyn-dns
dyn-resp dyn-scram dyn-snappy dyna-simd-core dyna-simd-scalar dyna-simd-neon dyna-simd-sse42 dyna-simd-avx2
dyna-simd-avx512 dyna-simd-sve dyna-nat dyna-aio dyna-aio-uring dyna-evloop dyna-file dyna-net dyna-http dyna-netip
dyna-net-tcp dyna-net-proxy dyna-net-dns dyna-net-redis dyna-net-pg dyna-net-ratelimit dyna-net-metrics
dyna-sdl dyn-ui dyna-ui dyna-ui-sdl"
MODULE_DEFINES="-DCONFIG_NATIVE_MODULE_FILE -DCONFIG_NATIVE_MODULE_NET"

engine_build(){
  [ -f "$ROOT/repl.c" ] || die "repl.c is generated by the host build: run ./build.sh build first"
  mkdir -p "$OUT/obj"
  (cd "$ROOT" && ./build.sh __cc-lines CONFIG_NATIVE_MODULES=y CONFIG_SDL3=y CONFIG_UI=y) > "$OUT/cc-lines.txt"
  : > "$OUT/jobs.txt"
  for o in $ENGINE_OBJS; do
    line=$(grep -F -- "-o .obj/$o.o " "$OUT/cc-lines.txt" || true)
    [ -n "$line" ] || die "build.sh __cc-lines printed no line for $o"
    extra=""
    [ "$o" = dyna-cli ] && extra="-Dmain=dyn_cli_main"
    printf '%s\n' "$line" | awk -v cc="$CC" -v out="$OUT/obj" -v inc="$OUT/sdl3-$SDL_VER/include" -v extra="$extra $MODULE_DEFINES" '{
      s = cc " -fPIC -isystem " inc " " extra
      for (i = 2; i <= NF; i++) {
        t = $i
        if (t ~ /^-DCONFIG_NATIVE_MODULE_/ || t == "-DCONFIG_SQLITE" || t == "-DCONFIG_ZSTD" || t == "-DCONFIG_TLS" || t ~ /^-I\/opt\/homebrew/) continue
        if (t == "-isystem" && $(i + 1) ~ /^\/opt\/homebrew/) { i++; continue }
        if (t ~ /^\.obj\//) t = out "/" substr(t, 6)
        s = s " " t
      }
      print s
    }' >> "$OUT/jobs.txt"
  done
  echo "android: compiling $(wc -l < "$OUT/jobs.txt" | tr -d ' ') engine objects"
  rm -rf "$OUT/jobs" && mkdir -p "$OUT/jobs" && : > "$OUT/compile.log"
  n=0
  while IFS= read -r line; do
    n=$((n + 1))
    printf 'cd "%s" || exit 255\n%s 2>> "%s" || { echo "FAILED: job %s" >> "%s"; exit 255; }\n' \
      "$ROOT" "$line" "$OUT/compile.log" "$n" "$OUT/compile.log" > "$OUT/jobs/$n.sh"
  done < "$OUT/jobs.txt"
  find "$OUT/jobs" -name '*.sh' -print0 | xargs -0 -n 1 -P "$(sysctl -n hw.ncpu 2>/dev/null || nproc)" sh \
    || { tail -40 "$OUT/compile.log"; die "engine compile failed -- log: $OUT/compile.log"; }
  $CC -fPIC -isystem "$OUT/sdl3-$SDL_VER/include" -I"$ROOT" -I"$ROOT/src" -O2 -Wall -c "$ROOT/tools/android/main.c" -o "$OUT/obj/android-main.o"
  mkdir -p "$OUT/apk/lib/$ABI"
  objs=""
  for o in $ENGINE_OBJS android-main; do objs="$objs $OUT/obj/$o.o"; done
  # shellcheck disable=SC2086
  $CC -shared -o "$OUT/apk/lib/$ABI/libmain.so" $objs -L"$OUT/sdl3-$SDL_VER/lib" -lSDL3 -lm -ldl -llog -landroid \
    -Wl,--no-undefined -Wl,-z,max-page-size=16384 || die "libmain.so link failed"
  cp "$OUT/sdl3-$SDL_VER/lib/libSDL3.so" "$OUT/apk/lib/$ABI/"
}

java_build(){
  rm -rf "$OUT/java" && mkdir -p "$OUT/java"
  javac --release 17 -nowarn -encoding UTF-8 -classpath "$JAR" -d "$OUT/java" \
    "$SDL_SRC"/android-project/app/src/main/java/org/libsdl/app/*.java "$ROOT"/tools/android/java/org/dynajs/app/*.java > "$OUT/javac.log" 2>&1 \
    || { cat "$OUT/javac.log"; die "javac failed"; }
  find "$OUT/java" -name '*.class' > "$OUT/classes.txt"
  # shellcheck disable=SC2046
  "$BT/d8" --min-api "$API" --lib "$JAR" --output "$OUT" $(cat "$OUT/classes.txt") || die "d8 failed"
}

apk_build(){
  app="$1"
  [ -f "$app" ] || die "no such app script: $app"
  rm -rf "$OUT/apk/assets" && mkdir -p "$OUT/apk/assets"
  # SDL resolves a relative path against internal storage before the assets, and main.c
  # writes the script there as app.js: the asset keeps a name that is never written.
  cp "$app" "$OUT/apk/assets/dynajs-app.js"
  "$BT/aapt2" link -o "$OUT/base.apk" --manifest "$ROOT/tools/android/AndroidManifest.xml" -I "$JAR" \
    --min-sdk-version "$API" --target-sdk-version 35 -A "$OUT/apk/assets" || die "aapt2 link failed"
  cp "$OUT/classes.dex" "$OUT/apk/classes.dex"
  (cd "$OUT/apk" && zip -q -r "$OUT/base.apk" classes.dex lib)
  "$BT/zipalign" -f -p 16 "$OUT/base.apk" "$OUT/aligned.apk"
  ks=$OUT/debug.keystore
  [ -f "$ks" ] || keytool -genkeypair -keystore "$ks" -storepass android -keypass android -alias dynajs \
    -keyalg RSA -keysize 2048 -validity 3650 -dname "CN=dynajs debug" > /dev/null 2>&1
  "$BT/apksigner" sign --ks "$ks" --ks-pass pass:android --key-pass pass:android --out "$OUT/dynajs.apk" "$OUT/aligned.apk"
  echo "android: $OUT/dynajs.apk ($(wc -c < "$OUT/dynajs.apk" | tr -d ' ') bytes)"
}

emulator_up(){
  "$ADB" get-state > /dev/null 2>&1 && return 0
  if ! "$SDK/cmdline-tools/latest/bin/avdmanager" list avd 2>/dev/null | grep -q "Name: $AVD\$"; then
    echo no | "$SDK/cmdline-tools/latest/bin/avdmanager" create avd -n "$AVD" -k "system-images;android-35;default;$ABI" -d pixel_7 > /dev/null
  fi
  echo "android: booting the $AVD emulator (headless)"
  nohup "$SDK/emulator/emulator" -avd "$AVD" -no-window -no-audio -no-boot-anim -no-snapshot -gpu swiftshader_indirect \
    > "$OUT/emulator.log" 2>&1 &
  "$ADB" wait-for-device
  n=0
  until [ "$("$ADB" shell getprop sys.boot_completed 2>/dev/null | tr -d '\r')" = 1 ]; do
    n=$((n + 1)); [ $n -lt 300 ] || die "the emulator did not boot in 300 s -- log: $OUT/emulator.log"
    sleep 1
  done
  n=0
  until "$ADB" shell dumpsys window 2>/dev/null | grep -q 'mCurrentFocus=.*launcher'; do
    n=$((n + 1)); [ $n -lt 120 ] || die "the emulator booted but its home screen never took focus in 120 s"
    sleep 1
  done
  echo "android: emulator ready"
}

app_log(){ "$ADB" shell run-as "$PKG" cat files/dynajs.log 2>/dev/null || true; }

cmd=${1:-}; [ $# -gt 0 ] && shift
mkdir -p "$OUT"
case "$cmd" in
  build) [ $# -ge 1 ] || die "usage: build APP.js"; tools_find; sdl_build; engine_build; java_build; apk_build "$1" ;;
  emulator) tools_find; emulator_up ;;
  run) [ $# -ge 1 ] || die "usage: run APP.js"; tools_find; sdl_build; engine_build; java_build; apk_build "$1"; emulator_up
       "$ADB" install -r "$OUT/dynajs.apk" > /dev/null
       "$ADB" shell am force-stop "$PKG"
       "$ADB" shell am start -W -n "$PKG/org.dynajs.app.DynaActivity" > /dev/null
       echo "android: launched $PKG" ;;
  log) tools_find; app_log ;;
  smoke) tools_find; sdl_build; engine_build; java_build; apk_build "$ROOT/tools/android/demo.js"; emulator_up
         "$ADB" install -r "$OUT/dynajs.apk" > /dev/null
         python3 -I "$ROOT/tools/android/smoke.py" "$ADB" ;;
  *) sed -n '2,17p' "$0"; exit 2 ;;
esac
