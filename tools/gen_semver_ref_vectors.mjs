import { createRequire } from "node:module";
const require = createRequire(new URL("../tmp_audit/noderef/package.json", import.meta.url));
const semver = require("semver");

const PRE = ["", "-0", "-1", "-alpha", "-alpha.1", "-alpha.beta", "-beta", "-beta.2", "-beta.11", "-rc.1", "-0.3.7", "-x.7.z.92", "-alpha.0a"];
const versions = [];
for (const M of [0, 1, 2])
    for (const m of [0, 1, 3])
        for (const p of [0, 2])
            for (const pre of ["", "-alpha", "-beta.2"]) versions.push(`${M}.${m}.${p}${pre}`);
for (const pre of PRE) versions.push(`1.2.3${pre}`, `1.2.3${pre}+build.5`);
versions.push("10.20.30", "1.0.0+20130313144700", "9007199254740991.0.0", "1.2.3-9007199254740991");
const invalid = ["1.2", "01.2.3", "1.02.3", "1.2.03", "1.2.3-", "1.2.3-01", "1.2.3+", "1.2.3-a..b", "v1.2.3", "=1.2.3", " 1.2.3 ",
    "1.2.3.4", "", "a.b.c", "1.2.3-alpha_beta", "9007199254740992.0.0", "-1.2.3", "1.2.3+build..x"];
const ranges = ["^1.2.3", "^0.2.3", "^0.0.3", "^0.0", "^0", "^1.x", "~1.2.3", "~1.2", "~1", "~0.2.3", "1.x", "1.2.x", "1.*", "*", "",
    "x", ">=1.2.3 <2.0.0", ">1.2.3", "<1.2.3", "<=1.2.3", ">=1.2.3", "=1.2.3", "1.2.3", "1.2.3 - 2.3.4", "1.2 - 2.3", "1 - 2",
    "<1.2.3 || >2.0.0", "1 || 2", "^1.2.3-beta.2", ">1.2.3-alpha.3", "~1.2.3-beta.2", "^0.0.0-0", ">=0.0.0", ">=1.2.3-0",
    "<2.0.0-0", ">=1.0.0 <1.0.1 || 2.x", "^2.0.0 || ~1.3.0", "1.2.3-alpha - 1.2.3-rc.1", ">=1.2.3-alpha.1 <1.2.3"];
const rows = [];
const add = (op, args, want) => rows.push([op, args, want]);

for (const v of [...versions, ...invalid]) {
    const ok = semver.valid(v) !== null;
    add("isValid", [v], ok);
    if (ok) {
        const s = semver.parse(v);
        add("parse", [v], { major: s.major, minor: s.minor, patch: s.patch, prerelease: s.prerelease, build: s.build, version: s.version });
        add("prerelease", [v], semver.prerelease(v));
    }
}
const valid = versions.filter((v) => semver.valid(v));
// compact rows: a version is "v<index into VALID>", a range "r<index into RANGES>"
const V = (v) => "v" + valid.indexOf(v);
const R = (r) => "r" + ranges.indexOf(r);
// every prerelease shape against every other (the precedence rules live
// there), and each of those against the release grid
const preForms = valid.filter((v) => v.startsWith("1.2.3"));
const grid = valid.filter((v) => !v.startsWith("1.2.3"));
for (const a of preForms) {
    for (const b of preForms) {
        add("compare", [V(a), V(b)], semver.compare(a, b));
        add("compareBuild", [V(a), V(b)], semver.compareBuild(a, b));
    }
    for (const b of grid.filter((_, i) => i % 3 === 0)) add("compare", [V(a), V(b)], semver.compare(a, b));
}
for (const a of grid)
    for (const b of grid.filter((_, i) => i % 2 === 0)) add("compare", [V(a), V(b)], semver.compare(a, b));
// sort: the contract is "ascending by precedence"; ties (build-only
// differences) are unordered by it, so the suite checks the property and
// not node-semver's compareBuild tie-break
add("sortProperty", ["@VALID_REVERSED"], true);
for (const r of ranges) {
    add("satisfiesAll", [R(r)], valid.map((v) => (semver.satisfies(v, r) ? "1" : "0")).join(""));
    add("maxSatisfying", ["@VALID", R(r)], semver.maxSatisfying(valid, r));
    add("minSatisfying", ["@VALID", R(r)], semver.minSatisfying(valid, r));
}
for (const a of ranges) add("intersectsAll", [R(a)], ranges.map((b) => (semver.intersects(a, b) ? "1" : "0")).join(""));
for (const v of ["1.2.3", "1.2.3-beta.4", "0.0.1", "1.2.0-rc.1", "1.0.0-0", "2.0.0-alpha.beta"])
    for (const rel of ["major", "minor", "patch", "premajor", "preminor", "prepatch", "prerelease"])
        for (const id of [undefined, "alpha", "beta"]) add("inc", [v, rel, id ?? null], semver.inc(v, rel, id));
for (const v of ["1.2.3", "1.2.3-beta.4", "2.0.0-rc.1+b"]) add("inc", [v, "release", null], semver.prerelease(v) ? semver.inc(v, "release") : null);
for (const v of ["  =1.2.3  ", "=1.2.3", "1.2.3", "1.2", "01.2.3", " 1.2.3-pre+b "]) add("clean", [v], semver.clean(v));

