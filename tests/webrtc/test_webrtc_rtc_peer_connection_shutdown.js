// flags: --std
// covers: dyna:webrtc.RTCPeerConnection -- engine teardown with live peer connections: a child dynajs leaves
// connections gathering (TURN transaction in flight), connected with data in flight, freshly constructed, or closed,
// then dies on an uncaught error or a rejected top-level await. A child also dies while eight default
// certificates are being generated on the CPU offload pool (DEC-b): the pending keygen jobs hold their connections and
// complete during teardown without touching freed state. DEC-b: the lazy default certificate (no certificates in the
// configuration) is generated by offload_cpu inside the operations chain, so createOffer/createAnswer and an implicit setLocalDescription() wait for it without
// blocking the loop; a close() during that wait drops the operation unsettled (webrtc-pc 4.4.1.2 chain, 4.4.1.5 close);
// --io-threads 0 has no pool, so the certificate is generated inline and the operation completes before close() runs.
// dc-throw: a connection that never gathered but has a data channel: the channel pins itself and its connection, so the
// connection registers its shutdown sweep at createDataChannel; before, teardown left the pair alive (gc_obj_list assert).
// Round 3: the createDataChannel pin is dropped again once every channel of a connection that never started its transport is
// closed, so 1000 such dropped connections are collected; one live channel keeps the pin and the shutdown sweep (dc-half-throw),
// and a connection with a running transport keeps its transport pin when its last channel closes.
// gencert-throw: generateCertificate jobs still on the pool at teardown: each job registers a shutdown sweep that frees its
// promise functions; the pool callback that runs later on an orphaned job frees only native memory. The shutdown sweep must close every transport without
// touching the already-freed timer table: the child must exit 1 with its own error, never a signal or sanitizer report.
// Round 4: a global read before any import resolves the lazy accessor by loading dyna:webrtc through the engine (JS_LoadModule,
// then JS_FindLoadedModule), never by evaluating source text at runtime; reading the namespace first crashed on the unlinked module.
// WebIDL 3.7 interface objects are data properties {writable, !enumerable, configurable}: the lazy accessor replaces all five
// with data properties on the first get (no import needed), and an assignment before first use stores a data property.
import { RTCPeerConnection } from "dyna:webrtc";
import { Exec, Which, getEnv } from "dyna:sys";
import { suite } from "../lib/kit.js";
import { LO, connectPair } from "./rtc_util.js";
import * as std from "std";

const t = suite("webrtc_shutdown");
const CHILD = "tests/webrtc/webrtc_shutdown_child.js";
const BIN = getEnv("DYNAJS_CHILD_BIN") || "./dynajs";
const TO = "tools/bounded-run.sh 30 30 webrtc-shutdown -- ";

function run(shape) {
    const r = Exec("/bin/sh", ["-c", TO + BIN + " " + CHILD + " " + shape]);
    return { rc: r.code, out: String(r.stdout), err: String(r.stderr) };
}

for (const [shape, ready, msg] of [
    ["gathering-throw", "READY gathering", "child boom"],
    ["connected-throw", "READY open", "child boom"],
    ["connected-reject", "READY open", "child reject"],
    ["fresh-throw", "READY new", "child boom"],
    ["closed-throw", "READY closed", "child boom"],
    ["keygen-throw", "READY keygen", "child boom"],
    ["dc-throw", "READY dc", "child boom"],
    ["dc-half-throw", "READY half closed", "child boom"],
    ["connected-dcclose-throw", "READY dcclosed closed", "child boom"],
    ["gencert-throw", "READY gencert", "child boom"],
]) {
    t.test(shape + ": exits 1 with the script's error and no teardown fault", async (a) => {
        a.eq(globalThis.RTCPeerConnection, RTCPeerConnection, "the child uses the same global class");
        const r = run(shape);
        a.ok(r.out.includes(ready), "child reached its state: " + r.out.trim().slice(0, 200));
        a.eq(r.rc, 1, "exit code (stderr: " + r.err.slice(0, 400) + ")");
        a.ok(r.err.includes(msg));
        a.ok(!/Sanitizer|Segmentation|Assertion failed|runtime error/.test(r.err), "no sanitizer or crash report");
    }, { timeoutMs: 40000 });
}

t.test("the default certificate is generated off the event loop: close() while createOffer waits for it never settles that createOffer; --io-threads 0 generates it inline (DEC-b)", async (a) => {
    for (const [flags, want] of [["--io-threads 2 ", "pending"], ["--io-threads 0 ", "resolved"]]) {
        const r = Exec("/bin/sh", ["-c", TO + BIN + " " + flags + CHILD + " keygen-close"]);
        const m = /KEYGEN (.*)/.exec(String(r.stdout));
        a.eq(r.code, 0, flags + "exit code (stderr: " + String(r.stderr).slice(0, 400) + ")");
        a.ok(!!m, flags + "child reported: " + String(r.stdout).slice(0, 200));
        const v = m ? JSON.parse(m[1]) : {};
        a.eq(v.st, want, flags + "createOffer on the pc closed while its certificate was being generated");
        a.eq(v.st2, want, flags + "a second createOffer queued behind the one waiting for the certificate");
        a.eq(v.st3, want, flags + "an implicit setLocalDescription() on a fresh pc waits for the certificate the same way");
        a.eq(v.sig, "closed", flags + "closed");
        a.eq(v.fp, true, flags + "two createOffer calls on one pc carry the same generated certificate");
        a.ok(!/Sanitizer|Segmentation|Assertion failed|runtime error/.test(String(r.stderr)), flags + "no sanitizer or crash report");
    }
}, { timeoutMs: 70000 });

t.test("a connection whose only data channels were closed before it ever gathered is collectable: 1000 dropped, at least 999 finalized (round 3)", async (a) => {
    let fin = 0;
    const reg = new FinalizationRegistry(() => { fin++; });
    const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
    for (let i = 0; i < 1000; i++) {
        const pc = new RTCPeerConnection(LO);
        const dc = pc.createDataChannel("x" + i);
        dc.close();
        reg.register(pc, i);
    }
    for (let k = 0; k < 6 && fin < 999; k++) { await sleep(20); std.gc(); await sleep(20); }
    a.ok(fin >= 999, "finalized " + fin + " of 1000");
    const kept = new RTCPeerConnection(LO);
    const kdc = kept.createDataChannel("k");
    let keptFin = 0;
    const reg2 = new FinalizationRegistry(() => { keptFin++; });
    reg2.register(kdc, 0);
    for (let k = 0; k < 3; k++) { await sleep(20); std.gc(); }
    a.eq(keptFin, 0, "an open channel on a never-gathered connection is still pinned until close()");
    a.eq(kdc.readyState, "connecting");
    kept.close();
    let live = 0, ref;
    const reg3 = new FinalizationRegistry(() => { live++; });
    await (async () => {
        const { a: pa, b: pb, dc } = await connectPair();
        const closed = new Promise((r) => { dc.onclose = r; });
        dc.close();
        await closed;
        reg3.register(pa, 0);
        ref = new WeakRef(pa);
        globalThis.__pbKeep = pb;
    })();
    for (let k = 0; k < 4; k++) { await sleep(20); std.gc(); }
    a.eq(live, 0, "a connected pc whose only channel closed stays a GC root while its transport runs");
    const pa = ref.deref();
    a.ok(!!pa && pa.connectionState === "connected", "still connected: " + (pa && pa.connectionState));
    if (pa) pa.close();
    globalThis.__pbKeep.close();
    delete globalThis.__pbKeep;
}, { timeoutMs: 30000 });

t.test("globals are lazy accessors until first use, then the module's own classes as writable non-enumerable data", async (a) => {
    const probe = "const d = Object.getOwnPropertyDescriptor(globalThis, 'RTCDataChannel');" +
        "const lazy = typeof d.get === 'function' && !d.enumerable;" +
        "const m = await import('dyna:webrtc');" +
        "const same = ['RTCPeerConnection','RTCDataChannel','RTCIceCandidate','RTCSessionDescription','RTCCertificate'].every((n) => globalThis[n] === m[n]);" +
        "const e = Object.getOwnPropertyDescriptor(globalThis, 'RTCDataChannel');" +
        "RTCCertificate = 7;" +
        "console.log(JSON.stringify([lazy, same, 'value' in e, e.writable, e.enumerable, e.configurable, RTCCertificate]));";
    const r = Exec(BIN, ["-e", probe]);
    a.eq(String(r.stdout).trim(), JSON.stringify([true, true, true, true, false, true, 7]), String(r.stderr));
    const cold = Exec(BIN, ["-e", "const C = RTCDataChannel; const m = await import('dyna:webrtc'); console.log(JSON.stringify([typeof C, C === m.RTCDataChannel]));"]);
    a.eq(cold.code, 0, "a global read before any import loads dyna:webrtc in C (stderr: " + String(cold.stderr).slice(0, 400) + ")");
    a.eq(String(cold.stdout).trim(), JSON.stringify(["function", true]), String(cold.stderr));
    const names = "['RTCPeerConnection','RTCDataChannel','RTCIceCandidate','RTCSessionDescription','RTCCertificate']";
    const shape = (n) => "(() => { const d = Object.getOwnPropertyDescriptor(globalThis, " + n + "); return [typeof d.value, 'get' in d, 'set' in d, d.writable, d.enumerable, d.configurable]; })()";
    const touched = Exec(BIN, ["-e", "const t = typeof RTCPeerConnection; console.log(JSON.stringify([t, " + names + ".map((n) => " + shape("n") + ")]));"]);
    const idl = ["function", false, false, true, false, true];
    a.eq(String(touched.stdout).trim(), JSON.stringify(["function", [idl, idl, idl, idl, idl]]),
        "WebIDL interface objects: one touch, no import, every global is a data property (stderr: " + String(touched.stderr).slice(0, 400) + ")");
    const assigned = Exec(BIN, ["-e", "RTCIceCandidate = 5; const d = Object.getOwnPropertyDescriptor(globalThis, 'RTCIceCandidate');" +
        "console.log(JSON.stringify([d.value, 'get' in d, d.writable, d.enumerable, d.configurable, typeof RTCSessionDescription]));"]);
    a.eq(String(assigned.stdout).trim(), JSON.stringify([5, false, true, false, true, "function"]),
        "an assignment before first use stores a writable data property and leaves the others lazy (stderr: " + String(assigned.stderr).slice(0, 400) + ")");
    a.eq(globalThis.RTCPeerConnection, RTCPeerConnection);
});

await t.run();
