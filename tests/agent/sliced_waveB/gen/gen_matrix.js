#!/usr/bin/env node
/* gen_matrix.js — committed generator for the sliced_waveB parametric
 * matrices. Run with node OR dynajs; emits self-validating assert probes
 * (expectations computed from the ES-spec reference implementations baked
 * into each emitted file, never console.log oracles).
 *
 * usage: node gen_matrix.js   (writes the m1/m3/m4 .js files into ../)
 * Emit then commit; the canonical runner (tests/agent/_h/run.sh) picks the
 * emitted files up like any other probe. */
var fs = require("fs");
var path = require("path");
var BASE64 = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789ab";
var dir = path.join(__dirname, "..");

function refLastIndexOfSrc() {
  return `
function refLastIndexOf(s, needle, from) {
  var n = s.length, m = needle.length;
  if (arguments.length < 3 || from === undefined || from !== from)
    from = Infinity;
  var k = Math.min(Math.max(from, 0), n - m);
  if (n - m < 0) return -1;
  while (k >= 0) { if (s.substring(k, k + m) === needle) return k; k--; }
  return -1;
}`;
}
function mkRndSrc() {
  return `
function mkRnd(n, seed, hi) {
  var s = "";
  var x = seed | 0;
  for (var i = 0; i < n; i++) {
    x = (x * 1103515245 + 12345) & 0x7fffffff;
    s += String.fromCharCode((hi ? 65 : 97) + (x >>> 16) % 26);
  }
  return s;
}
function mkWide(n, seed) {
  var s = "\\u1450";
  var x = seed | 0;
  for (var i = 0; i < n; i++) {
    x = (x * 1103515245 + 12345) & 0x7fffffff;
    s += String.fromCharCode(0x100 + (x >>> 16) % 500);
  }
  return s;
}
function mkWideNarrowable(n) {
  var s = "\\u1450";
  for (var i = 0; i < n; i++) s += String.fromCharCode(0xF7 - (i % 90));
  return s;
}
function lit64() { return "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789ab"; }`;
}

/* ---- m1: atom-parent slice matrices (literal parents, T1) -------------- */
var lens = [64, 65, 100, 127, 128, 255, 256, 1000];
var offs = [0, 1, 63, 100];
var m1 = `/* GENERATED by gen_matrix.js — T1 atom-parent slice matrices.
 * Literal parents longer than the slice threshold; ops compared against
 * the spec substring reference. */
` + mkRndSrc() + `
var LIT1024 = "` + BASE64.repeat(16) + `";
var WLIT = "\u0101" + "\u0102\u0103\u0104".repeat(341) + "\u0105\u0106"; /* 1026 wide units */
`;
for (var li = 0; li < lens.length; li++) {
  for (var oi = 0; oi < offs.length; oi++) {
    var len = lens[li], off = offs[oi];
    if (off + 1 + len > 1024) continue;
    m1 += `
test("m1_narrow_l` + len + `_o` + off + `", function () {
  var start = ` + (off + 1) + `, end = start + ` + len + `;
  var want = LIT1024.substring(start, end);
  var got = LIT1024.slice(start, end);
  ok(got === want, "content");
  eq(got.length, ` + len + `, "length");
  eq(got.charCodeAt(0), want.charCodeAt(0), "first unit");
  eq(got.charCodeAt(got.length - 1), want.charCodeAt(want.length - 1), "last unit");
});
`;
  }
}
m1 += `
test("m1_wide_sweep", function () {
  var starts = [0, 1, 63, 100, 500], lens = [1, 63, 64, 65, 255, 256, 1000];
  for (var si = 0; si < starts.length; si++) {
    for (var li = 0; li < lens.length; li++) {
      var st = starts[si], en = st + lens[li];
      if (en > WLIT.length) continue;
      var want = WLIT.substring(st, en), got = WLIT.slice(st, en);
      ok(got === want, "wide st=" + st + " len=" + lens[li]);
      eq(got.charCodeAt(0), want.charCodeAt(0), "first unit");
    }
  }
});
summary("sliced_waveB");
`;
fs.writeFileSync(path.join(dir, "m1_atom_slice_matrix.js"), m1);

/* ---- m3: lastIndexOf / indexOf matrices over slices (T3) --------------- */
var m3 = `/* GENERATED by gen_matrix.js — T3 search matrices over slice windows.
 * Every case diffed against refLastIndexOf (ES spec) / indexOf symmetry. */
` + mkRndSrc() + refLastIndexOfSrc() + `
var P = mkRnd(50000, 101, false);
var PW = mkWide(20000, 102);
var sliceSizes = [100, 1024, 1025, 4096, 16384, 50000];
`;
m3 += `
test("m3_lidx_matrix", function () {
  var seeds = [1, 2, 3];
  for (var si = 0; si < sliceSizes.length; si++) {
    var L = sliceSizes[si];
    var S = P.slice(0, L);
    for (var ni = 0; ni < 6; ni++) {
      var ndLen = [1, 2, 5, 30][ni % 4];
      var pos = (ni * 7919 + si * 104729) % Math.max(1, L - ndLen);
      var nd = P.substring(pos, pos + ndLen);
      var got = S.lastIndexOf(nd);
      var want = refLastIndexOf(S, nd, undefined);
      eq(got, want, "lidx L=" + L + " pos=" + pos + " nl=" + ndLen);
      var fi = S.indexOf(nd);
      ok(fi <= got && got <= L, "idx<=lidx L=" + L + " pos=" + pos);
      ok(fi < 0 || S.substring(fi, fi + nd.length) === nd, "idx match valid L=" + L);
      for (var f = 0; f < 4; f++) {
        var from = [undefined, 0, pos, L][f];
        eq(S.lastIndexOf(nd, from), refLastIndexOf(S, nd, from),
           "lidx from L=" + L + " pos=" + pos + " f=" + f);
      }
    }
    var absent = "QQ-absent-" + si;
    eq(S.lastIndexOf(absent), -1, "lidx absent L=" + L);
    eq(S.indexOf(absent), -1, "idx absent L=" + L);
    var across = P.substring(L - 5, L + 5);
    var fi = S.indexOf(across);
    /* across content may recur inside a random haystack; the invariant is
       that any match lies wholly inside the window */
    ok(fi === -1 || fi <= L - 10, "across-end match wholly inside L=" + L);
  }
});
test("m3_lidx_wide_matrix", function () {
  for (var si = 0; si < sliceSizes.length; si++) {
    var L = Math.min(sliceSizes[si], PW.length);
    var S = PW.slice(0, L);
    for (var ni = 0; ni < 4; ni++) {
      var pos = (ni * 6007 + si * 8191) % Math.max(1, L - 8);
      var nd = PW.substring(pos, pos + 8);
      eq(S.lastIndexOf(nd), refLastIndexOf(S, nd, undefined),
         "wide lidx L=" + L + " pos=" + pos);
      eq(S.indexOf(nd), refLastIndexOf(S, nd, undefined) === -1 ? -1 : S.indexOf(nd),
         "wide idx sanity L=" + L);
    }
  }
});
summary("sliced_waveB");
`;
fs.writeFileSync(path.join(dir, "m3_search_matrix.js"), m3);

/* ---- m4: narrow-at-flatten matrices (T4) -------------------------------- */
var m4 = `/* GENERATED by gen_matrix.js — T4 narrow-at-flatten content matrices.
 * Wide all-latin1 slices + short/long concats; content compared to the
 * spec concatenation. */
` + mkRndSrc() + `
var sizes = [64, 65, 127, 128, 255, 256, 1000, 2000];
var WN = mkWideNarrowable(3000);
`;
m4 += `
test("m4_flatten_matrix", function () {
  for (var i = 0; i < sizes.length; i++) {
    var L = sizes[i];
    var S = WN.slice(1, 1 + L);
    var tail = S + "xy";
    ok(tail === WN.substring(1, 1 + L) + "xy", "tail L=" + L);
    var head = "xy" + S;
    ok(head === "xy" + WN.substring(1, 1 + L), "head L=" + L);
    var both = S + S;
    ok(both === WN.substring(1, 1 + L) + WN.substring(1, 1 + L), "both L=" + L);
    eq(tail.length, L + 2, "tail length L=" + L);
    eq(tail.charCodeAt(L), 120, "first tail unit L=" + L);
  }
});
test("m4_genuine_wide_untouched", function () {
  var G = mkWide(2000, 77);
  var S = G.slice(0, 2000);
  var r = S + "x";
  ok(r === G.substring(0, 2000) + "x", "genuine wide concat content");
  eq(r.charCodeAt(r.length - 1), 120, "narrow tail unit");
  ok(r.indexOf("\\u1450") === 0, "wide head intact");
});
summary("sliced_waveB");
`;
fs.writeFileSync(path.join(dir, "m4_narrow_flatten_matrix.js"), m4);

console.log("generated:m1_atom_slice_matrix.js m3_search_matrix.js m4_narrow_flatten_matrix.js");
